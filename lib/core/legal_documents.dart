/// Абзац или маркированный список внутри раздела документа.
sealed class LegalBlock {
  const LegalBlock();
}

final class LegalParagraph extends LegalBlock {
  const LegalParagraph(this.text);

  final String text;
}

final class LegalList extends LegalBlock {
  const LegalList(this.items);

  final List<String> items;
}

class LegalSection {
  const LegalSection({this.heading, required this.blocks});

  final String? heading;
  final List<LegalBlock> blocks;
}

class LegalDocument {
  const LegalDocument({
    required this.title,
    required this.shortTitle,
    required this.edition,
    required this.sections,
  });

  final String title;

  /// Для шапки экрана: полное название в неё не помещается.
  final String shortTitle;

  final String edition;
  final List<LegalSection> sections;
}

